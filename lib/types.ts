export type Ride = {
  id: string;
  driverId: string;
  driverName: string;
  origin: string;
  campus: string;
  destination: string;
  departure: string;
  seats: number;
  priceCents: number;
  car: string;
  notes: string;
  status: string;
  removalReportId?: string | null;
  version: number;
  createdAt: string;
  accepted: number;
};
export type Booking = {
  id: string;
  rideId: string;
  riderId: string;
  riderName: string;
  status: string;
  createdAt: string;
};
export type User = { userId: string; displayName: string };
export type Message = {
  id: string;
  bookingId: string;
  senderId: string;
  senderName: string;
  body: string;
  createdAt: string;
  hidden?: boolean;
};
export type Conversation = { messages: Message[]; canSend: boolean };
export type Snapshot = {
  rides: Ride[];
  bookings: Booking[];
  user: User | null;
  profile?: Profile | null;
  isModerator?: boolean;
};
export type Profile = { displayName: string; campus: string };
export type RideSearchResult = {
  rides: Ride[];
  hasMore: boolean;
  nextCursor: string | null;
  campuses: string[];
};
export type Report = {
  id: string;
  rideId: string;
  reason: string;
  details: string;
  status: string;
  resolution: string | null;
  resolutionNotes: string | null;
  createdAt: string;
  origin: string;
  destination: string;
  driverName: string;
  kind?: "ride" | "message";
  messageId?: string;
  messageText?: string;
  messageSenderName?: string;
  rideStatus?: string;
};
export type Appeal = {
  id: string;
  rideId: string;
  removalReportId: string;
  driverName: string;
  origin: string;
  destination: string;
  details: string;
  status: string;
  decisionNotes: string | null;
  createdAt: string;
};
